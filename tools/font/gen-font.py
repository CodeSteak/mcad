#!/usr/bin/env python3
"""Generates crates/cad-render/src/font.rs: anti-aliased bitmap glyphs (4-bit alpha) of
DejaVu Sans Mono for the labels of `mcad render` (no font dependency at run time).

    python3 tools/font/gen-font.py [/pfad/DejaVuSansMono.ttf]

DejaVu fonts: Bitstream Vera license (free use, embedding allowed), see the generated file.
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
CHARS = "".join(chr(c) for c in range(32, 127)) + "äöüÄÖÜß°×²³µ–·→Øø±"
SIZES = [("SMALL", 11), ("LARGE", 16)]
OUT = Path(__file__).resolve().parents[2] / "crates/cad-render/src/font.rs"
HEX = "0123456789abcdef"


def render(size):
    font = ImageFont.truetype(TTF, size)
    asc, desc = font.getmetrics()
    w = round(font.getlength("M"))
    h = asc + desc
    rows = []
    for ch in CHARS:
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        px = img.load()
        rows.append("".join(HEX[min(15, (px[x, y] + 8) // 17)] for y in range(h) for x in range(w)))
    return w, h, asc, rows


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    out = [
        "//! Bitmap glyphs (4-bit alpha, one hex digit per pixel, rows top to bottom) of DejaVu Sans",
        "//! Mono, generated by `tools/font/gen-font.py`. Do not edit.",
        "//!",
        "//! DejaVu fonts are based on Bitstream Vera (Copyright (c) 2003 by Bitstream, Inc.; DejaVu",
        "//! changes are in the public domain); the Bitstream Vera license permits embedding.",
        "",
        f"pub const CHARS: &str = {rust_str(CHARS)};",
        "",
        "pub struct Font {",
        "    pub w: u32,",
        "    pub h: u32,",
        "    pub glyphs: &'static [&'static str],",
        "}",
    ]
    for name, size in SIZES:
        w, h, asc, rows = render(size)
        out.append("")
        out.append(f"pub const {name}: Font = Font {{")
        out.append(f"    w: {w},")
        out.append(f"    h: {h},")
        out.append("    glyphs: &[")
        for r in rows:
            # long rows are split so rustfmt's line width holds
            parts = [r[i : i + 96] for i in range(0, len(r), 96)]
            if len(parts) == 1:
                out.append(f'        "{r}",')
            else:
                out.append("        concat!(")
                for p in parts:
                    out.append(f'            "{p}",')
                out.append("        ),")
        out.append("    ],")
        out.append("};")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT}: {len(CHARS)} glyphs, sizes {[s for _, s in SIZES]}")


main()
