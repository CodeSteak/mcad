#!/usr/bin/env bash
# Builds the engine for the browser worker:
#   crates/cad-wasm (wasm32-unknown-unknown) → wasm-bindgen --target web → web/src/wasm-pkg/
# plus a copy of smlib.js / smlib.wasm (Emscripten SMLib kernel) next to it.
#
#   web/scripts/build-wasm.sh [--debug] [--no-opt]
#
# * wasm-bindgen-cli is installed in the version of the `wasm-bindgen` crate in Cargo.lock
#   if the installed one differs (cargo install --locked).
# * wasm-opt (PATH, or emsdk's upstream/bin) runs with -O3 unless --no-opt.
# * smlib.js/.wasm come from web/public/smlib/ (built by smlib/build-wasm.sh, which is run
#   if they are missing).
#
# Output (gitignored): web/src/wasm-pkg/{cad_wasm.js, cad_wasm_bg.wasm, cad_wasm.d.ts,
# snippets/, smlib-bridge.js (stable re-export of the kernel bridge), smlib.js, smlib.wasm}.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
WEB="$(cd "$HERE/.." && pwd)"
ROOT="$(cd "$WEB/.." && pwd)"
OUT="$WEB/src/wasm-pkg"
PROFILE=release
OPT=1
for a in "$@"; do
  case "$a" in
    --debug) PROFILE=debug ;;
    --no-opt) OPT=0 ;;
    *) echo "unknown argument: $a" >&2; exit 2 ;;
  esac
done

# 1. Rust → wasm32
cargo_flags=(-p cad-wasm --target wasm32-unknown-unknown)
[ "$PROFILE" = release ] && cargo_flags+=(--release)
(cd "$ROOT" && "${CARGO:-cargo}" build "${cargo_flags[@]}")
WASM="$ROOT/target/wasm32-unknown-unknown/$PROFILE/cad_wasm.wasm"

# 2. wasm-bindgen-cli in the version of the crate
want=$(awk '/^name = "wasm-bindgen"$/ { getline; gsub(/version = |"/, ""); print; exit }' "$ROOT/Cargo.lock")
have=$(wasm-bindgen --version 2>/dev/null | awk '{ print $2 }' || true)
if [ "$have" != "$want" ]; then
  echo "installing wasm-bindgen-cli $want (found: ${have:-none})"
  "${CARGO:-cargo}" install wasm-bindgen-cli --version "$want" --locked
fi

rm -rf "$OUT"
mkdir -p "$OUT"
wasm-bindgen --target web --out-dir "$OUT" "$WASM"

# 3. wasm-opt
if [ "$OPT" = 1 ]; then
  WASM_OPT="$(command -v wasm-opt || true)"
  if [ -z "$WASM_OPT" ]; then
    for c in "${EMSDK:-/opt/tools/emsdk}/upstream/bin/wasm-opt"; do
      [ -x "$c" ] && WASM_OPT="$c"
    done
  fi
  if [ -n "$WASM_OPT" ]; then
    "$WASM_OPT" -O3 --enable-bulk-memory --enable-nontrapping-float-to-int --enable-sign-ext \
      --enable-mutable-globals --enable-reference-types --enable-multivalue \
      "$OUT/cad_wasm_bg.wasm" -o "$OUT/cad_wasm_bg.opt.wasm" \
      && mv "$OUT/cad_wasm_bg.opt.wasm" "$OUT/cad_wasm_bg.wasm" \
      || echo "wasm-opt failed; keeping the unoptimised module" >&2
  else
    echo "wasm-opt not found; skipping" >&2
  fi
fi

# 4. Stable path to the kernel bridge (the snippet directory name contains a hash). Importing
#    it through this re-export keeps the same module instance as cad_wasm.js uses.
bridge=$(cd "$OUT" && find snippets -name smlib-bridge.js | head -n 1)
[ -n "$bridge" ] || { echo "smlib-bridge.js not found in snippets" >&2; exit 1; }
cat > "$OUT/smlib-bridge.js" <<EOF
// Generated by web/scripts/build-wasm.sh: stable re-export of the kernel-smlib JS bridge.
export * from "./$bridge";
EOF
cat > "$OUT/smlib-bridge.d.ts" <<'EOF'
export function initSmlib(factory: unknown, options?: Record<string, unknown>): Promise<unknown>;
export function smlibReady(): boolean;
export function smlibModule(): unknown;
EOF

# 5. SMLib kernel (Emscripten)
if [ ! -f "$WEB/public/smlib/smlib.wasm" ] || [ ! -f "$WEB/public/smlib/smlib.js" ]; then
  "$ROOT/smlib/build-wasm.sh" "$WEB/public/smlib"
fi
cp -f "$WEB/public/smlib/smlib.js" "$WEB/public/smlib/smlib.wasm" "$OUT/"
cat > "$OUT/smlib.d.ts" <<'EOF'
declare const createSmlib: (options?: Record<string, unknown>) => Promise<unknown>;
export default createSmlib;
EOF

for f in "$OUT/cad_wasm_bg.wasm" "$OUT/smlib.wasm"; do
  raw=$(stat -c %s "$f")
  gz=$(gzip -9 -c "$f" | wc -c)
  echo "$(basename "$f"): $raw B, gzip -9 $gz B"
done
echo "-> $OUT"
